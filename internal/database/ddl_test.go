func TestRelationKind(t *testing.T) {
	tests := []struct {
		in   string
		want ObjectKind
	}{
		{"table", ObjectTable},
		{"view", ObjectView},
		{"VIEW", ObjectView},
		{"materialized view", ObjectMatView},
		{"partitioned table", ObjectTable},
		{"", ObjectTable},
	}
	for _, tc := range tests {
		if got := RelationKind(tc.in); got != tc.want {
			t.Errorf("RelationKind(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

func TestObjectKindIsRelation(t *testing.T) {
	for _, k := range []ObjectKind{ObjectTable, ObjectView, ObjectMatView} {
		if !k.IsRelation() {
			t.Errorf("%q should be a relation", k)
		}
	}
	for _, k := range []ObjectKind{ObjectIndex, ObjectConstraint, ObjectTrigger, ObjectFunction, ObjectProcedure} {
		if k.IsRelation() {
			t.Errorf("%q should not be a relation", k)
		}
	}
}
