func TestRenderColumn(t *testing.T) {
	tests := []struct {
		name string
		col  DDLColumn
		want string
	}{
		{
			name: "plain nullable",
			col:  DDLColumn{Name: "email", Type: "text"},
			want: `"email" text`,
		},
		{
			name: "not null with default",
			col:  DDLColumn{Name: "created_at", Type: "timestamptz", NotNull: true, Default: "now()"},
			want: `"created_at" timestamptz DEFAULT now() NOT NULL`,
		},
		{
			name: "identity outranks default",
			col:  DDLColumn{Name: "id", Type: "bigint", NotNull: true, Identity: "BY DEFAULT", Default: "ignored"},
			want: `"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		},
		{
			name: "generated column carries no default",
			col:  DDLColumn{Name: "total", Type: "numeric", Generated: "qty * price", Default: "ignored"},
			want: `"total" numeric GENERATED ALWAYS AS (qty * price) STORED`,
		},
		{
			name: "explicit collation",
			col:  DDLColumn{Name: "name", Type: "text", Collation: "C"},
			want: `"name" text COLLATE "C"`,
		},
		{
			name: "embedded quote is escaped",
			col:  DDLColumn{Name: `we"ird`, Type: "text"},
			want: `"we""ird" text`,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := RenderColumn(DriverPostgres, tc.col); got != tc.want {
				t.Errorf("RenderColumn()\n got %s\nwant %s", got, tc.want)
			}
		})
	}
}

func TestComposeCreateTable(t *testing.T) {
	got := ComposeCreateTable(DriverPostgres, "public", "users",
		[]DDLColumn{
			{Name: "id", Type: "bigint", NotNull: true, Identity: "BY DEFAULT"},
			{Name: "email", Type: "text", NotNull: true},
		},
		[]string{`CONSTRAINT "users_pkey" PRIMARY KEY ("id")`})

	want := `CREATE TABLE "public"."users" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "email" text NOT NULL,
    CONSTRAINT "users_pkey" PRIMARY KEY ("id")
);`
	if got != want {
		t.Errorf("ComposeCreateTable()\n got %s\nwant %s", got, want)
	}
}

func TestComposeCreateTableMySQLQuoting(t *testing.T) {
	got := ComposeCreateTable(DriverMySQL, "shop", "orders",
		[]DDLColumn{{Name: "id", Type: "int", NotNull: true}}, nil)
	if !strings.Contains(got, "`shop`.`orders`") || !strings.Contains(got, "`id` int NOT NULL") {
		t.Errorf("MySQL DDL should use backticks, got %s", got)
	}
}

