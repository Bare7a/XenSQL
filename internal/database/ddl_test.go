func TestRenderConstraint(t *testing.T) {
	tests := []struct {
		name string
		in   ConstraintInfo
		want string
	}{
		{
			name: "engine definition wins over synthesis",
			in:   ConstraintInfo{Name: "ck_age", Type: "CHECK", Definition: "CHECK ((age > 0))"},
			want: `CONSTRAINT "ck_age" CHECK ((age > 0))`,
		},
		{
			name: "synthesized primary key",
			in:   ConstraintInfo{Name: "users_pkey", Type: "PRIMARY KEY", Columns: []string{"id"}},
			want: `CONSTRAINT "users_pkey" PRIMARY KEY ("id")`,
		},
		{
			name: "synthesized composite unique",
			in:   ConstraintInfo{Name: "u_ab", Type: "UNIQUE", Columns: []string{"a", "b"}},
			want: `CONSTRAINT "u_ab" UNIQUE ("a", "b")`,
		},
		{
			name: "synthesized foreign key",
			in: ConstraintInfo{
				Name: "fk_org", Type: "FOREIGN KEY", Columns: []string{"org_id"},
				RefTable: "orgs", RefColumns: []string{"id"},
			},
			want: `CONSTRAINT "fk_org" FOREIGN KEY ("org_id") REFERENCES "orgs" ("id")`,
		},
		{
			name: "unnamed constraint drops the CONSTRAINT prefix",
			in:   ConstraintInfo{Type: "PRIMARY KEY", Columns: []string{"id"}},
			want: `PRIMARY KEY ("id")`,
		},
		{
			name: "check without definition is skipped",
			in:   ConstraintInfo{Name: "ck", Type: "CHECK"},
			want: "",
		},
		{
			name: "primary key without columns is skipped",
			in:   ConstraintInfo{Name: "pk", Type: "PRIMARY KEY"},
			want: "",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := RenderConstraint(DriverPostgres, tc.in); got != tc.want {
				t.Errorf("RenderConstraint()\n got %q\nwant %q", got, tc.want)
			}
		})
	}
}

func TestRenderCreateIndex(t *testing.T) {
	tests := []struct {
		name   string
		driver DriverType
		in     IndexInfo
		want   string
	}{
		{
			name:   "unique index with method",
			driver: DriverPostgres,
			in: IndexInfo{
				Name: "users_email_idx", Schema: "public", Table: "users",
				Columns: []string{"email"}, IsUnique: true, Method: "btree",
			},
			want: `CREATE UNIQUE INDEX "users_email_idx" ON "public"."users" USING btree ("email");`,
		},
		{
			name:   "mysql drops the method",
			driver: DriverMySQL,
			in: IndexInfo{
				Name: "idx_a", Schema: "shop", Table: "orders",
				Columns: []string{"a", "b"}, Method: "btree",
			},
			want: "CREATE INDEX `idx_a` ON `shop`.`orders` (`a`, `b`);",
		},
		{
			name:   "primary key index has no standalone form",
			driver: DriverPostgres,
			in:     IndexInfo{Name: "users_pkey", Table: "users", Columns: []string{"id"}, IsPrimary: true},
			want:   "",
		},
		{
			name:   "expression-only index has no columns to render",
			driver: DriverPostgres,
			in:     IndexInfo{Name: "idx_expr", Table: "users"},
			want:   "",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := RenderCreateIndex(tc.driver, tc.in); got != tc.want {
				t.Errorf("RenderCreateIndex()\n got %q\nwant %q", got, tc.want)
			}
		})
	}
}

func TestJoinDDL(t *testing.T) {
	got := JoinDDL("CREATE TABLE a ();", "", "  \n", "CREATE INDEX i ON a (x);")
	want := "CREATE TABLE a ();\n\nCREATE INDEX i ON a (x);"
	if got != want {
		t.Errorf("JoinDDL() = %q, want %q", got, want)
	}
	if got := JoinDDL("", ""); got != "" {
		t.Errorf("JoinDDL of nothing = %q, want empty", got)
	}
}

